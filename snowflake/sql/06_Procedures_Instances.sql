CREATE OR REPLACE PROCEDURE <% database %>.OMD.INSERT_INTO_EVENT_LOG
(
    P_EVENT_DETAIL        VARCHAR,
    P_MODULE_INSTANCE_ID  NUMBER DEFAULT 0,
    P_BATCH_INSTANCE_ID   NUMBER DEFAULT 0,
    P_EVENT_TYPE_CODE     NUMBER DEFAULT 2,
    P_EVENT_RETURN_CODE   VARCHAR DEFAULT NULL,
    P_ERROR_BITMAP        NUMBER DEFAULT NULL
)
RETURNS NUMBER
LANGUAGE SQL
COMMENT = 'Writes an event to OMD.EVENT_LOG. The Batch Instance Id is derived from the Module Instance when it is not given. Returns the Event Id.'
EXECUTE AS OWNER
AS
$$
DECLARE
    V_EVENT_ID NUMBER;
    V_BATCH_INSTANCE_ID NUMBER;
BEGIN
    V_BATCH_INSTANCE_ID := COALESCE(P_BATCH_INSTANCE_ID, 0);
    IF (V_BATCH_INSTANCE_ID = 0 AND COALESCE(P_MODULE_INSTANCE_ID, 0) <> 0) THEN
        SELECT COALESCE(MAX(BATCH_INSTANCE_ID), 0) INTO :V_BATCH_INSTANCE_ID FROM <% database %>.OMD.MODULE_INSTANCE WHERE MODULE_INSTANCE_ID = :P_MODULE_INSTANCE_ID;
    END IF;

    SELECT <% database %>.OMD.EVENT_LOG_SEQ.NEXTVAL INTO :V_EVENT_ID;

    INSERT INTO <% database %>.OMD.EVENT_LOG (EVENT_ID, BATCH_INSTANCE_ID, MODULE_INSTANCE_ID, EVENT_TYPE_CODE, EVENT_TIMESTAMP, EVENT_RETURN_CODE, EVENT_DETAIL, ERROR_BITMAP)
    VALUES (:V_EVENT_ID, :V_BATCH_INSTANCE_ID, COALESCE(:P_MODULE_INSTANCE_ID, 0), COALESCE(:P_EVENT_TYPE_CODE, 2), SYSDATE(), :P_EVENT_RETURN_CODE, LEFT(:P_EVENT_DETAIL, 4000), :P_ERROR_BITMAP);

    RETURN V_EVENT_ID;
END;
$$;

CREATE OR REPLACE PROCEDURE <% database %>.OMD.UPDATE_MODULE_INSTANCE
(
    P_MODULE_INSTANCE_ID  NUMBER,
    P_EVENT_CODE          VARCHAR,
    P_ROWS_INPUT          NUMBER DEFAULT 0,
    P_ROWS_INSERTED       NUMBER DEFAULT 0,
    P_ROWS_UPDATED        NUMBER DEFAULT 0,
    P_ROWS_DELETED        NUMBER DEFAULT 0,
    P_ROWS_DISCARDED      NUMBER DEFAULT 0,
    P_ROWS_REJECTED       NUMBER DEFAULT 0
)
RETURNS VARCHAR
LANGUAGE SQL
COMMENT = 'Applies an event (Proceed, Cancel, Abort, Rollback, Success, Failure) to a Module Instance and sets its status columns accordingly.'
EXECUTE AS OWNER
AS
$$
BEGIN
    CASE (P_EVENT_CODE)
        WHEN 'Proceed' THEN
            UPDATE <% database %>.OMD.MODULE_INSTANCE SET INTERNAL_PROCESSING_CODE = 'Proceed' WHERE MODULE_INSTANCE_ID = :P_MODULE_INSTANCE_ID;
        WHEN 'Rollback' THEN
            UPDATE <% database %>.OMD.MODULE_INSTANCE SET INTERNAL_PROCESSING_CODE = 'Rollback' WHERE MODULE_INSTANCE_ID = :P_MODULE_INSTANCE_ID;
        WHEN 'Cancel' THEN
            UPDATE <% database %>.OMD.MODULE_INSTANCE SET INTERNAL_PROCESSING_CODE = 'Cancel', NEXT_RUN_STATUS_CODE = 'Proceed', EXECUTION_STATUS_CODE = 'Cancelled', END_TIMESTAMP = SYSDATE() WHERE MODULE_INSTANCE_ID = :P_MODULE_INSTANCE_ID;
        WHEN 'Abort' THEN
            UPDATE <% database %>.OMD.MODULE_INSTANCE SET INTERNAL_PROCESSING_CODE = 'Abort', NEXT_RUN_STATUS_CODE = 'Proceed', EXECUTION_STATUS_CODE = 'Aborted', END_TIMESTAMP = SYSDATE() WHERE MODULE_INSTANCE_ID = :P_MODULE_INSTANCE_ID;
        WHEN 'Success' THEN
            UPDATE <% database %>.OMD.MODULE_INSTANCE
            SET NEXT_RUN_STATUS_CODE = 'Proceed', EXECUTION_STATUS_CODE = 'Succeeded', END_TIMESTAMP = SYSDATE(),
                ROWS_INPUT = :P_ROWS_INPUT, ROWS_INSERTED = :P_ROWS_INSERTED, ROWS_UPDATED = :P_ROWS_UPDATED, ROWS_DELETED = :P_ROWS_DELETED, ROWS_DISCARDED = :P_ROWS_DISCARDED, ROWS_REJECTED = :P_ROWS_REJECTED
            WHERE MODULE_INSTANCE_ID = :P_MODULE_INSTANCE_ID;
        WHEN 'Failure' THEN
            UPDATE <% database %>.OMD.MODULE_INSTANCE
            SET NEXT_RUN_STATUS_CODE = 'Rollback', EXECUTION_STATUS_CODE = 'Failed', END_TIMESTAMP = SYSDATE(),
                ROWS_INPUT = :P_ROWS_INPUT, ROWS_INSERTED = :P_ROWS_INSERTED, ROWS_UPDATED = :P_ROWS_UPDATED, ROWS_DELETED = :P_ROWS_DELETED, ROWS_DISCARDED = :P_ROWS_DISCARDED, ROWS_REJECTED = :P_ROWS_REJECTED
            WHERE MODULE_INSTANCE_ID = :P_MODULE_INSTANCE_ID;
        ELSE
            RETURN 'Unknown event code ''' || COALESCE(P_EVENT_CODE, '') || '''.';
    END CASE;
    RETURN 'Module Instance ' || TO_VARCHAR(P_MODULE_INSTANCE_ID) || ' received event ''' || P_EVENT_CODE || '''.';
END;
$$;

CREATE OR REPLACE PROCEDURE <% database %>.OMD.UPDATE_BATCH_INSTANCE
(
    P_BATCH_INSTANCE_ID  NUMBER,
    P_EVENT_CODE         VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
COMMENT = 'Applies an event (Proceed, Cancel, Abort, Rollback, Success, Failure) to a Batch Instance and sets its status columns accordingly.'
EXECUTE AS OWNER
AS
$$
BEGIN
    CASE (P_EVENT_CODE)
        WHEN 'Proceed' THEN
            UPDATE <% database %>.OMD.BATCH_INSTANCE SET INTERNAL_PROCESSING_CODE = 'Proceed' WHERE BATCH_INSTANCE_ID = :P_BATCH_INSTANCE_ID;
        WHEN 'Rollback' THEN
            UPDATE <% database %>.OMD.BATCH_INSTANCE SET INTERNAL_PROCESSING_CODE = 'Rollback' WHERE BATCH_INSTANCE_ID = :P_BATCH_INSTANCE_ID;
        WHEN 'Cancel' THEN
            UPDATE <% database %>.OMD.BATCH_INSTANCE SET INTERNAL_PROCESSING_CODE = 'Cancel', NEXT_RUN_STATUS_CODE = 'Proceed', EXECUTION_STATUS_CODE = 'Cancelled', END_TIMESTAMP = SYSDATE() WHERE BATCH_INSTANCE_ID = :P_BATCH_INSTANCE_ID;
        WHEN 'Abort' THEN
            UPDATE <% database %>.OMD.BATCH_INSTANCE SET INTERNAL_PROCESSING_CODE = 'Abort', NEXT_RUN_STATUS_CODE = 'Proceed', EXECUTION_STATUS_CODE = 'Aborted', END_TIMESTAMP = SYSDATE() WHERE BATCH_INSTANCE_ID = :P_BATCH_INSTANCE_ID;
        WHEN 'Success' THEN
            UPDATE <% database %>.OMD.BATCH_INSTANCE SET NEXT_RUN_STATUS_CODE = 'Proceed', EXECUTION_STATUS_CODE = 'Succeeded', END_TIMESTAMP = SYSDATE() WHERE BATCH_INSTANCE_ID = :P_BATCH_INSTANCE_ID;
        WHEN 'Failure' THEN
            -- A failed Batch keeps 'Proceed' as next run status: the next run skips the Modules that succeeded and rolls back the ones that failed.
            UPDATE <% database %>.OMD.BATCH_INSTANCE SET NEXT_RUN_STATUS_CODE = 'Proceed', EXECUTION_STATUS_CODE = 'Failed', END_TIMESTAMP = SYSDATE() WHERE BATCH_INSTANCE_ID = :P_BATCH_INSTANCE_ID;
        ELSE
            RETURN 'Unknown event code ''' || COALESCE(P_EVENT_CODE, '') || '''.';
    END CASE;
    RETURN 'Batch Instance ' || TO_VARCHAR(P_BATCH_INSTANCE_ID) || ' received event ''' || P_EVENT_CODE || '''.';
END;
$$;

CREATE OR REPLACE PROCEDURE <% database %>.OMD.CREATE_BATCH_INSTANCE
(
    P_BATCH_CODE               VARCHAR,
    P_PARENT_BATCH_INSTANCE_ID NUMBER DEFAULT 0,
    P_EXECUTION_CONTEXT        VARCHAR DEFAULT ''
)
RETURNS NUMBER
LANGUAGE SQL
COMMENT = 'Creates a Batch Instance in the Executing state and returns its Id. Registers the Batch and the parent relationship when the settings allow it.'
EXECUTE AS OWNER
AS
$$
DECLARE
    V_BATCH_ID NUMBER;
    V_PARENT_BATCH_ID NUMBER;
    V_BATCH_INSTANCE_ID NUMBER;
    V_EXISTS NUMBER;
    V_MESSAGE VARCHAR;
BEGIN
    V_BATCH_ID := <% database %>.OMD.GET_BATCH_ID_BY_CODE(P_BATCH_CODE);

    IF (V_BATCH_ID IS NULL) THEN
        IF (<% database %>.OMD_METADATA.GET_SETTING_FLAG('AUTO_REGISTER_BATCHES') = 'Y') THEN
            CALL <% database %>.OMD.REGISTER_BATCH(:P_BATCH_CODE) INTO :V_BATCH_ID;
        END IF;
        IF (V_BATCH_ID IS NULL) THEN
            V_MESSAGE := 'The Batch ''' || COALESCE(P_BATCH_CODE, '') || ''' is not registered and automatic registration is off.';
            CALL <% database %>.OMD.INSERT_INTO_EVENT_LOG(:V_MESSAGE);
            RETURN NULL;
        END IF;
    END IF;

    -- A child Batch must be registered under its parent.
    IF (COALESCE(P_PARENT_BATCH_INSTANCE_ID, 0) <> 0) THEN
        V_PARENT_BATCH_ID := <% database %>.OMD.GET_BATCH_ID_BY_BATCH_INSTANCE_ID(P_PARENT_BATCH_INSTANCE_ID);
        IF (V_PARENT_BATCH_ID IS NOT NULL AND V_PARENT_BATCH_ID <> V_BATCH_ID) THEN
            SELECT COUNT(*) INTO :V_EXISTS FROM <% database %>.OMD.BATCH_HIERARCHY WHERE PARENT_BATCH_ID = :V_PARENT_BATCH_ID AND BATCH_ID = :V_BATCH_ID;
            IF (V_EXISTS = 0 AND <% database %>.OMD_METADATA.GET_SETTING_FLAG('AUTO_REGISTER_RELATIONSHIPS') = 'Y') THEN
                CALL <% database %>.OMD.ADD_BATCH_TO_PARENT_BATCH(:P_BATCH_CODE, <% database %>.OMD.GET_BATCH_CODE_BY_ID(:V_PARENT_BATCH_ID));
            END IF;
        END IF;
    END IF;

    SELECT <% database %>.OMD.BATCH_INSTANCE_SEQ.NEXTVAL INTO :V_BATCH_INSTANCE_ID;

    INSERT INTO <% database %>.OMD.BATCH_INSTANCE (BATCH_INSTANCE_ID, BATCH_ID, PARENT_BATCH_INSTANCE_ID, START_TIMESTAMP, END_TIMESTAMP, INTERNAL_PROCESSING_CODE, NEXT_RUN_STATUS_CODE, EXECUTION_STATUS_CODE, EXECUTION_CONTEXT)
    VALUES (:V_BATCH_INSTANCE_ID, :V_BATCH_ID, COALESCE(:P_PARENT_BATCH_INSTANCE_ID, 0), SYSDATE(), NULL, 'Abort', 'Proceed', 'Executing', LEFT(COALESCE(:P_EXECUTION_CONTEXT, ''), 4000));

    RETURN V_BATCH_INSTANCE_ID;
END;
$$;

CREATE OR REPLACE PROCEDURE <% database %>.OMD.CREATE_MODULE_INSTANCE
(
    P_MODULE_CODE        VARCHAR,
    P_BATCH_INSTANCE_ID  NUMBER DEFAULT 0,
    P_EXECUTION_CONTEXT  VARCHAR DEFAULT '',
    P_QUERY              VARCHAR DEFAULT NULL
)
RETURNS NUMBER
LANGUAGE SQL
COMMENT = 'Creates a Module Instance in the Executing state and returns its Id. The executed code (the query, or the registered executable) is stored by checksum. Registers the Module and the Batch/Module relationship when the settings allow it.'
EXECUTE AS OWNER
AS
$$
DECLARE
    V_MODULE_ID NUMBER;
    V_BATCH_ID NUMBER;
    V_MODULE_INSTANCE_ID NUMBER;
    V_EXECUTED_CODE VARCHAR;
    V_CHECKSUM VARCHAR;
    V_EXISTS NUMBER;
    V_MESSAGE VARCHAR;
BEGIN
    V_MODULE_ID := <% database %>.OMD.GET_MODULE_ID_BY_CODE(P_MODULE_CODE);

    IF (V_MODULE_ID IS NULL) THEN
        IF (<% database %>.OMD_METADATA.GET_SETTING_FLAG('AUTO_REGISTER_MODULES') = 'Y') THEN
            CALL <% database %>.OMD.REGISTER_MODULE(:P_MODULE_CODE, COALESCE(:P_QUERY, 'SELECT NULL')) INTO :V_MODULE_ID;
        END IF;
        IF (V_MODULE_ID IS NULL) THEN
            V_MESSAGE := 'The Module ''' || COALESCE(P_MODULE_CODE, '') || ''' is not registered and automatic registration is off.';
            CALL <% database %>.OMD.INSERT_INTO_EVENT_LOG(:V_MESSAGE, 0, :P_BATCH_INSTANCE_ID);
            RETURN NULL;
        END IF;
    END IF;

    -- A Module that runs from a Batch must be registered for that Batch.
    IF (COALESCE(P_BATCH_INSTANCE_ID, 0) <> 0) THEN
        V_BATCH_ID := <% database %>.OMD.GET_BATCH_ID_BY_BATCH_INSTANCE_ID(P_BATCH_INSTANCE_ID);
        IF (V_BATCH_ID IS NOT NULL) THEN
            SELECT COUNT(*) INTO :V_EXISTS FROM <% database %>.OMD.BATCH_MODULE WHERE BATCH_ID = :V_BATCH_ID AND MODULE_ID = :V_MODULE_ID;
            IF (V_EXISTS = 0 AND <% database %>.OMD_METADATA.GET_SETTING_FLAG('AUTO_REGISTER_RELATIONSHIPS') = 'Y') THEN
                CALL <% database %>.OMD.ADD_MODULE_TO_BATCH(:P_MODULE_CODE, <% database %>.OMD.GET_BATCH_CODE_BY_ID(:V_BATCH_ID));
            END IF;
        END IF;
    END IF;

    -- The executed code, stored once per distinct text.
    IF (P_QUERY IS NULL) THEN
        SELECT MAX(EXECUTABLE) INTO :V_EXECUTED_CODE FROM <% database %>.OMD.MODULE WHERE MODULE_ID = :V_MODULE_ID;
    ELSE
        V_EXECUTED_CODE := P_QUERY;
    END IF;

    IF (V_EXECUTED_CODE IS NULL OR V_EXECUTED_CODE = '') THEN
        V_CHECKSUM := REPEAT('0', 128);
    ELSE
        V_CHECKSUM := SHA2(V_EXECUTED_CODE, 512);
        SELECT COUNT(*) INTO :V_EXISTS FROM <% database %>.OMD.MODULE_INSTANCE_EXECUTED_CODE WHERE CHECKSUM = :V_CHECKSUM;
        IF (V_EXISTS = 0) THEN
            INSERT INTO <% database %>.OMD.MODULE_INSTANCE_EXECUTED_CODE (CHECKSUM, EXECUTED_CODE) VALUES (:V_CHECKSUM, :V_EXECUTED_CODE);
        END IF;
    END IF;

    SELECT <% database %>.OMD.MODULE_INSTANCE_SEQ.NEXTVAL INTO :V_MODULE_INSTANCE_ID;

    INSERT INTO <% database %>.OMD.MODULE_INSTANCE (MODULE_INSTANCE_ID, MODULE_ID, BATCH_INSTANCE_ID, START_TIMESTAMP, END_TIMESTAMP, INTERNAL_PROCESSING_CODE, NEXT_RUN_STATUS_CODE, EXECUTION_STATUS_CODE, EXECUTION_CONTEXT, EXECUTED_CODE_CHECKSUM)
    VALUES (:V_MODULE_INSTANCE_ID, :V_MODULE_ID, COALESCE(:P_BATCH_INSTANCE_ID, 0), SYSDATE(), NULL, 'Abort', 'Proceed', 'Executing', LEFT(COALESCE(:P_EXECUTION_CONTEXT, ''), 4000), :V_CHECKSUM);

    RETURN V_MODULE_INSTANCE_ID;
END;
$$;

CREATE OR REPLACE PROCEDURE <% database %>.OMD.SET_SOURCE_CONTROL_VALUES
(
    P_MODULE_INSTANCE_ID  NUMBER,
    P_START_VALUE         VARCHAR,
    P_END_VALUE           VARCHAR
)
RETURNS NUMBER
LANGUAGE SQL
COMMENT = 'Records the load window of a Module Instance in OMD.SOURCE_CONTROL. Returns the Source Control Id.'
EXECUTE AS OWNER
AS
$$
DECLARE
    V_MODULE_ID NUMBER;
    V_SOURCE_CONTROL_ID NUMBER;
BEGIN
    V_MODULE_ID := <% database %>.OMD.GET_MODULE_ID_BY_MODULE_INSTANCE_ID(P_MODULE_INSTANCE_ID);
    IF (V_MODULE_ID IS NULL OR P_START_VALUE IS NULL) THEN
        RETURN NULL;
    END IF;

    SELECT <% database %>.OMD.SOURCE_CONTROL_SEQ.NEXTVAL INTO :V_SOURCE_CONTROL_ID;

    INSERT INTO <% database %>.OMD.SOURCE_CONTROL (SOURCE_CONTROL_ID, MODULE_ID, MODULE_INSTANCE_ID, INSERT_TIMESTAMP, START_VALUE, END_VALUE)
    VALUES (:V_SOURCE_CONTROL_ID, :V_MODULE_ID, :P_MODULE_INSTANCE_ID, SYSDATE(), LEFT(:P_START_VALUE, 100), LEFT(:P_END_VALUE, 100));

    RETURN V_SOURCE_CONTROL_ID;
END;
$$;
