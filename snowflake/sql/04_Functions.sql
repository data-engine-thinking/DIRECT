-- A setting value, or NULL when the setting does not exist or is inactive.
CREATE OR REPLACE FUNCTION <% database %>.OMD_METADATA.GET_SETTING(P_CODE VARCHAR)
RETURNS VARCHAR
AS
$$
    SELECT MAX(VALUE) FROM <% database %>.OMD_METADATA.FRAMEWORK_METADATA WHERE CODE = P_CODE AND ACTIVE_INDICATOR = 'Y'
$$;

-- A setting flag: 'Y' when the setting is Y (any case), otherwise 'N'.
CREATE OR REPLACE FUNCTION <% database %>.OMD_METADATA.GET_SETTING_FLAG(P_CODE VARCHAR)
RETURNS VARCHAR
AS
$$
    SELECT IFF(UPPER(COALESCE(MAX(VALUE), 'N')) = 'Y', 'Y', 'N') FROM <% database %>.OMD_METADATA.FRAMEWORK_METADATA WHERE CODE = P_CODE AND ACTIVE_INDICATOR = 'Y'
$$;

CREATE OR REPLACE FUNCTION <% database %>.OMD_METADATA.GET_FRAMEWORK_VERSION()
RETURNS VARCHAR
AS
$$
    SELECT COALESCE(<% database %>.OMD_METADATA.GET_SETTING('DIRECT_VERSION'), 'Unknown') || ' (' || COALESCE(<% database %>.OMD_METADATA.GET_SETTING('DIRECT_EDITION'), 'Unknown') || ')'
$$;

-- A timestamp as text, in the configured format (UTC).
CREATE OR REPLACE FUNCTION <% database %>.OMD_METADATA.GET_TIMESTAMP_STRING(P_TIMESTAMP TIMESTAMP_NTZ)
RETURNS VARCHAR
AS
$$
    SELECT TO_VARCHAR(P_TIMESTAMP, COALESCE(<% database %>.OMD_METADATA.GET_SETTING('TIMESTAMP_FORMAT'), 'YYYY-MM-DD HH24:MI:SS.FF7'))
$$;

CREATE OR REPLACE FUNCTION <% database %>.OMD.GET_BATCH_ID_BY_CODE(P_BATCH_CODE VARCHAR)
RETURNS NUMBER
AS
$$
    SELECT MAX(BATCH_ID) FROM <% database %>.OMD.BATCH WHERE BATCH_CODE = P_BATCH_CODE
$$;

CREATE OR REPLACE FUNCTION <% database %>.OMD.GET_MODULE_ID_BY_CODE(P_MODULE_CODE VARCHAR)
RETURNS NUMBER
AS
$$
    SELECT MAX(MODULE_ID) FROM <% database %>.OMD.MODULE WHERE MODULE_CODE = P_MODULE_CODE
$$;

CREATE OR REPLACE FUNCTION <% database %>.OMD.GET_BATCH_CODE_BY_ID(P_BATCH_ID NUMBER)
RETURNS VARCHAR
AS
$$
    SELECT MAX(BATCH_CODE) FROM <% database %>.OMD.BATCH WHERE BATCH_ID = P_BATCH_ID
$$;

CREATE OR REPLACE FUNCTION <% database %>.OMD.GET_MODULE_ID_BY_MODULE_INSTANCE_ID(P_MODULE_INSTANCE_ID NUMBER)
RETURNS NUMBER
AS
$$
    SELECT MAX(MODULE_ID) FROM <% database %>.OMD.MODULE_INSTANCE WHERE MODULE_INSTANCE_ID = P_MODULE_INSTANCE_ID
$$;

CREATE OR REPLACE FUNCTION <% database %>.OMD.GET_BATCH_ID_BY_BATCH_INSTANCE_ID(P_BATCH_INSTANCE_ID NUMBER)
RETURNS NUMBER
AS
$$
    SELECT MAX(BATCH_ID) FROM <% database %>.OMD.BATCH_INSTANCE WHERE BATCH_INSTANCE_ID = P_BATCH_INSTANCE_ID
$$;

-- The Batch Id a Module Instance ran under (0 when it ran stand-alone).
CREATE OR REPLACE FUNCTION <% database %>.OMD.GET_BATCH_ID_BY_MODULE_INSTANCE_ID(P_MODULE_INSTANCE_ID NUMBER)
RETURNS NUMBER
AS
$$
    SELECT COALESCE(MAX(bi.BATCH_ID), 0)
    FROM <% database %>.OMD.MODULE_INSTANCE mi
    JOIN <% database %>.OMD.BATCH_INSTANCE bi ON mi.BATCH_INSTANCE_ID = bi.BATCH_INSTANCE_ID
    WHERE mi.MODULE_INSTANCE_ID = P_MODULE_INSTANCE_ID
$$;

-- The active indicator of a Batch/Module relationship: 'Y', 'N', or 'U' when the relationship does not exist.
CREATE OR REPLACE FUNCTION <% database %>.OMD.GET_BATCH_MODULE_ACTIVE_INDICATOR_VALUE(P_BATCH_ID NUMBER, P_MODULE_ID NUMBER)
RETURNS VARCHAR
AS
$$
    SELECT COALESCE(MAX(ACTIVE_INDICATOR), 'U') FROM <% database %>.OMD.BATCH_MODULE WHERE BATCH_ID = P_BATCH_ID AND MODULE_ID = P_MODULE_ID
$$;

-- The most recent load window value of a Module: 1 = start value, 2 = end value.
CREATE OR REPLACE FUNCTION <% database %>.OMD.GET_MODULE_LOAD_WINDOW_VALUE(P_MODULE_ID NUMBER, P_START_OR_END NUMBER)
RETURNS VARCHAR
AS
$$
    SELECT MAX_BY(IFF(P_START_OR_END = 1, START_VALUE, END_VALUE), SOURCE_CONTROL_ID)
    FROM <% database %>.OMD.SOURCE_CONTROL
    WHERE MODULE_ID = P_MODULE_ID
$$;
