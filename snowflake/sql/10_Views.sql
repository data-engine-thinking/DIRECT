CREATE OR REPLACE VIEW <% database %>.OMD_PROCESSING.VW_BATCH_HIERARCHY AS
SELECT
    p.BATCH_ID    AS PARENT_BATCH_ID,
    p.BATCH_CODE  AS PARENT_BATCH_CODE,
    c.BATCH_ID    AS BATCH_ID,
    c.BATCH_CODE  AS BATCH_CODE,
    bh.SEQUENCE,
    bh.ACTIVE_INDICATOR
FROM <% database %>.OMD.BATCH_HIERARCHY bh
JOIN <% database %>.OMD.BATCH p ON bh.PARENT_BATCH_ID = p.BATCH_ID
JOIN <% database %>.OMD.BATCH c ON bh.BATCH_ID = c.BATCH_ID;

CREATE OR REPLACE VIEW <% database %>.OMD_PROCESSING.VW_BATCH_MODULE AS
SELECT
    b.BATCH_ID,
    b.BATCH_CODE,
    m.MODULE_ID,
    m.MODULE_CODE,
    m.MODULE_TYPE,
    m.AREA_CODE,
    bm.SEQUENCE,
    bm.ACTIVE_INDICATOR,
    m.DATA_OBJECT_SOURCE,
    m.DATA_OBJECT_TARGET,
    m.EXECUTABLE
FROM <% database %>.OMD.BATCH_MODULE bm
JOIN <% database %>.OMD.BATCH b ON bm.BATCH_ID = b.BATCH_ID
JOIN <% database %>.OMD.MODULE m ON bm.MODULE_ID = m.MODULE_ID;

-- The active on-demand Batches that are not executing, in the order of their last run (the oldest first).
CREATE OR REPLACE VIEW <% database %>.OMD_PROCESSING.VW_QUEUE_BATCH_PROCESSING AS
SELECT
    b.BATCH_ID,
    b.BATCH_CODE,
    COALESCE(MAX(bi.END_TIMESTAMP), '0001-01-01'::TIMESTAMP_NTZ) AS END_TIMESTAMP,
    ROW_NUMBER() OVER (ORDER BY COALESCE(MAX(bi.END_TIMESTAMP), '0001-01-01'::TIMESTAMP_NTZ)) AS QUEUE_ORDER
FROM <% database %>.OMD.BATCH b
LEFT JOIN <% database %>.OMD.BATCH_INSTANCE bi ON b.BATCH_ID = bi.BATCH_ID
WHERE b.BATCH_ID <> 0
  AND b.ACTIVE_INDICATOR = 'Y'
  AND b.FREQUENCY_CODE = 'On-demand'
  AND NOT EXISTS (SELECT 1 FROM <% database %>.OMD.BATCH_INSTANCE x WHERE x.BATCH_ID = b.BATCH_ID AND x.EXECUTION_STATUS_CODE = 'Executing')
GROUP BY b.BATCH_ID, b.BATCH_CODE;

CREATE OR REPLACE VIEW <% database %>.OMD_REPORTING.VW_EXECUTION_LOG_BATCH_INSTANCE AS
SELECT
    bi.BATCH_INSTANCE_ID,
    b.BATCH_CODE,
    bi.PARENT_BATCH_INSTANCE_ID,
    bi.EXECUTION_CONTEXT,
    bi.START_TIMESTAMP,
    bi.END_TIMESTAMP,
    DATEDIFF(second, bi.START_TIMESTAMP, bi.END_TIMESTAMP) AS EXECUTION_TIME,
    bi.INTERNAL_PROCESSING_CODE,
    bi.NEXT_RUN_STATUS_CODE,
    bi.EXECUTION_STATUS_CODE,
    es.EXECUTION_STATUS_DESCRIPTION
FROM <% database %>.OMD.BATCH_INSTANCE bi
JOIN <% database %>.OMD.BATCH b ON bi.BATCH_ID = b.BATCH_ID
LEFT JOIN <% database %>.OMD_METADATA.EXECUTION_STATUS es ON bi.EXECUTION_STATUS_CODE = es.EXECUTION_STATUS_CODE
WHERE bi.BATCH_INSTANCE_ID <> 0;

CREATE OR REPLACE VIEW <% database %>.OMD_REPORTING.VW_EXECUTION_LOG_MODULE_INSTANCE AS
SELECT
    mi.MODULE_INSTANCE_ID,
    m.MODULE_CODE,
    m.MODULE_TYPE,
    m.AREA_CODE,
    mi.BATCH_INSTANCE_ID,
    b.BATCH_CODE,
    mi.EXECUTION_CONTEXT,
    mi.START_TIMESTAMP,
    mi.END_TIMESTAMP,
    DATEDIFF(second, mi.START_TIMESTAMP, mi.END_TIMESTAMP) AS EXECUTION_TIME,
    mi.INTERNAL_PROCESSING_CODE,
    mi.NEXT_RUN_STATUS_CODE,
    mi.EXECUTION_STATUS_CODE,
    es.EXECUTION_STATUS_DESCRIPTION,
    mi.ROWS_INPUT,
    mi.ROWS_INSERTED,
    mi.ROWS_UPDATED,
    mi.ROWS_DELETED,
    mi.ROWS_DISCARDED,
    mi.ROWS_REJECTED,
    sc.START_VALUE,
    sc.END_VALUE
FROM <% database %>.OMD.MODULE_INSTANCE mi
JOIN <% database %>.OMD.MODULE m ON mi.MODULE_ID = m.MODULE_ID
LEFT JOIN <% database %>.OMD.BATCH_INSTANCE bi ON mi.BATCH_INSTANCE_ID = bi.BATCH_INSTANCE_ID
LEFT JOIN <% database %>.OMD.BATCH b ON bi.BATCH_ID = b.BATCH_ID
LEFT JOIN <% database %>.OMD_METADATA.EXECUTION_STATUS es ON mi.EXECUTION_STATUS_CODE = es.EXECUTION_STATUS_CODE
LEFT JOIN <% database %>.OMD.SOURCE_CONTROL sc ON mi.MODULE_INSTANCE_ID = sc.MODULE_INSTANCE_ID
WHERE mi.MODULE_INSTANCE_ID <> 0;

CREATE OR REPLACE VIEW <% database %>.OMD_REPORTING.VW_EXECUTION_EVENT_LOG AS
SELECT
    el.EVENT_ID,
    el.BATCH_INSTANCE_ID,
    b.BATCH_CODE,
    el.MODULE_INSTANCE_ID,
    m.MODULE_CODE,
    el.EVENT_TYPE_CODE,
    et.EVENT_TYPE_DESCRIPTION,
    el.EVENT_TIMESTAMP,
    el.EVENT_RETURN_CODE,
    el.EVENT_DETAIL,
    el.ERROR_BITMAP
FROM <% database %>.OMD.EVENT_LOG el
LEFT JOIN <% database %>.OMD_METADATA.EVENT_TYPE et ON el.EVENT_TYPE_CODE = et.EVENT_TYPE_CODE
LEFT JOIN <% database %>.OMD.BATCH_INSTANCE bi ON el.BATCH_INSTANCE_ID = bi.BATCH_INSTANCE_ID
LEFT JOIN <% database %>.OMD.BATCH b ON bi.BATCH_ID = b.BATCH_ID
LEFT JOIN <% database %>.OMD.MODULE_INSTANCE mi ON el.MODULE_INSTANCE_ID = mi.MODULE_INSTANCE_ID
LEFT JOIN <% database %>.OMD.MODULE m ON mi.MODULE_ID = m.MODULE_ID;

-- The current load window of every Module: the end of the last recorded window is the start of the next.
CREATE OR REPLACE VIEW <% database %>.OMD_REPORTING.VW_LOAD_WINDOWS AS
SELECT
    m.MODULE_ID,
    m.MODULE_CODE,
    m.DATA_OBJECT_SOURCE,
    m.DATA_OBJECT_TARGET,
    sc.MODULE_INSTANCE_ID AS LAST_MODULE_INSTANCE_ID,
    sc.INSERT_TIMESTAMP   AS LAST_LOAD_TIMESTAMP,
    sc.START_VALUE        AS LAST_START_VALUE,
    sc.END_VALUE          AS LAST_END_VALUE
FROM <% database %>.OMD.MODULE m
LEFT JOIN <% database %>.OMD.SOURCE_CONTROL sc ON m.MODULE_ID = sc.MODULE_ID
WHERE m.MODULE_ID <> 0
QUALIFY ROW_NUMBER() OVER (PARTITION BY m.MODULE_ID ORDER BY sc.SOURCE_CONTROL_ID DESC NULLS LAST) = 1;

-- Modules that failed in the last three months, with their average duration and failure count.
CREATE OR REPLACE VIEW <% database %>.OMD_REPORTING.VW_MODULE_FAILURES AS
SELECT
    m.MODULE_CODE,
    m.MODULE_DESCRIPTION,
    AVG(DATEDIFF(second, mi.START_TIMESTAMP, mi.END_TIMESTAMP)) AS AVG_EXECUTION_SECONDS,
    SUM(IFF(mi.EXECUTION_STATUS_CODE = 'Failed', 1, 0)) AS COUNT_ERRORS
FROM <% database %>.OMD.MODULE m
JOIN <% database %>.OMD.MODULE_INSTANCE mi ON m.MODULE_ID = mi.MODULE_ID
WHERE mi.START_TIMESTAMP > DATEADD(month, -3, SYSDATE())
GROUP BY m.MODULE_CODE, m.MODULE_DESCRIPTION
HAVING SUM(IFF(mi.EXECUTION_STATUS_CODE = 'Failed', 1, 0)) > 0;

-- Instances that have been executing for more than an hour.
CREATE OR REPLACE VIEW <% database %>.OMD_REPORTING.VW_EXCEPTIONS_LONG_RUNNING_PROCESSES AS
SELECT 'Batch' AS INSTANCE_TYPE, bi.BATCH_INSTANCE_ID AS INSTANCE_ID, b.BATCH_CODE AS CODE, bi.START_TIMESTAMP, DATEDIFF(minute, bi.START_TIMESTAMP, SYSDATE()) AS MINUTES_RUNNING
FROM <% database %>.OMD.BATCH_INSTANCE bi
JOIN <% database %>.OMD.BATCH b ON bi.BATCH_ID = b.BATCH_ID
WHERE bi.EXECUTION_STATUS_CODE = 'Executing' AND bi.START_TIMESTAMP < DATEADD(hour, -1, SYSDATE())
UNION ALL
SELECT 'Module', mi.MODULE_INSTANCE_ID, m.MODULE_CODE, mi.START_TIMESTAMP, DATEDIFF(minute, mi.START_TIMESTAMP, SYSDATE())
FROM <% database %>.OMD.MODULE_INSTANCE mi
JOIN <% database %>.OMD.MODULE m ON mi.MODULE_ID = m.MODULE_ID
WHERE mi.EXECUTION_STATUS_CODE = 'Executing' AND mi.START_TIMESTAMP < DATEADD(hour, -1, SYSDATE());
