-- Repository

CREATE TABLE IF NOT EXISTS <% database %>.OMD.BATCH
(
    BATCH_ID           NUMBER(38,0)   NOT NULL,
    BATCH_CODE         VARCHAR(500)   NOT NULL,
    BATCH_TYPE         VARCHAR(100),
    FREQUENCY_CODE     VARCHAR(100)   NOT NULL DEFAULT 'On-demand',
    ACTIVE_INDICATOR   VARCHAR(1)     NOT NULL DEFAULT 'Y',
    BATCH_DESCRIPTION  VARCHAR(4000),
    CONSTRAINT PK_BATCH PRIMARY KEY (BATCH_ID),
    CONSTRAINT UK_BATCH_CODE UNIQUE (BATCH_CODE)
);

CREATE TABLE IF NOT EXISTS <% database %>.OMD.BATCH_HIERARCHY
(
    PARENT_BATCH_ID    NUMBER(38,0)   NOT NULL,
    BATCH_ID           NUMBER(38,0)   NOT NULL,
    SEQUENCE           NUMBER(38,0)   NOT NULL DEFAULT 0,
    ACTIVE_INDICATOR   VARCHAR(1)     NOT NULL DEFAULT 'Y',
    CONSTRAINT PK_BATCH_HIERARCHY PRIMARY KEY (PARENT_BATCH_ID, BATCH_ID)
);

CREATE TABLE IF NOT EXISTS <% database %>.OMD.BATCH_INSTANCE
(
    BATCH_INSTANCE_ID         NUMBER(38,0)    NOT NULL,
    BATCH_ID                  NUMBER(38,0)    NOT NULL,
    PARENT_BATCH_INSTANCE_ID  NUMBER(38,0)    NOT NULL DEFAULT 0,
    START_TIMESTAMP           TIMESTAMP_NTZ   NOT NULL,
    END_TIMESTAMP             TIMESTAMP_NTZ,
    INTERNAL_PROCESSING_CODE  VARCHAR(100)    NOT NULL,
    NEXT_RUN_STATUS_CODE      VARCHAR(100)    NOT NULL,
    EXECUTION_STATUS_CODE     VARCHAR(100)    NOT NULL,
    EXECUTION_CONTEXT         VARCHAR(4000),
    CONSTRAINT PK_BATCH_INSTANCE PRIMARY KEY (BATCH_INSTANCE_ID)
);

CREATE TABLE IF NOT EXISTS <% database %>.OMD.MODULE
(
    MODULE_ID           NUMBER(38,0)   NOT NULL,
    MODULE_CODE         VARCHAR(500)   NOT NULL,
    MODULE_TYPE         VARCHAR(100)   NOT NULL DEFAULT 'DataLogistics',
    DATA_OBJECT_SOURCE  VARCHAR(1000)  NOT NULL DEFAULT 'N/A',
    DATA_OBJECT_TARGET  VARCHAR(1000)  NOT NULL DEFAULT 'N/A',
    AREA_CODE           VARCHAR(100)   NOT NULL DEFAULT 'MAINT',
    FREQUENCY_CODE      VARCHAR(100)   NOT NULL DEFAULT 'On-demand',
    ACTIVE_INDICATOR    VARCHAR(1)     NOT NULL DEFAULT 'Y',
    MODULE_DESCRIPTION  VARCHAR(4000),
    EXECUTABLE          VARCHAR,
    CONSTRAINT PK_MODULE PRIMARY KEY (MODULE_ID),
    CONSTRAINT UK_MODULE_CODE UNIQUE (MODULE_CODE)
);

CREATE TABLE IF NOT EXISTS <% database %>.OMD.BATCH_MODULE
(
    BATCH_ID           NUMBER(38,0)   NOT NULL,
    MODULE_ID          NUMBER(38,0)   NOT NULL,
    SEQUENCE           NUMBER(38,0)   NOT NULL DEFAULT 0,
    ACTIVE_INDICATOR   VARCHAR(1)     NOT NULL DEFAULT 'Y',
    CONSTRAINT PK_BATCH_MODULE PRIMARY KEY (BATCH_ID, MODULE_ID)
);

CREATE TABLE IF NOT EXISTS <% database %>.OMD.MODULE_INSTANCE
(
    MODULE_INSTANCE_ID        NUMBER(38,0)    NOT NULL,
    MODULE_ID                 NUMBER(38,0)    NOT NULL,
    BATCH_INSTANCE_ID         NUMBER(38,0)    NOT NULL DEFAULT 0,
    START_TIMESTAMP           TIMESTAMP_NTZ   NOT NULL,
    END_TIMESTAMP             TIMESTAMP_NTZ,
    INTERNAL_PROCESSING_CODE  VARCHAR(100)    NOT NULL,
    NEXT_RUN_STATUS_CODE      VARCHAR(100)    NOT NULL,
    EXECUTION_STATUS_CODE     VARCHAR(100)    NOT NULL,
    EXECUTION_CONTEXT         VARCHAR(4000),
    ROWS_INPUT                NUMBER(38,0),
    ROWS_INSERTED             NUMBER(38,0),
    ROWS_UPDATED              NUMBER(38,0),
    ROWS_DELETED              NUMBER(38,0),
    ROWS_DISCARDED            NUMBER(38,0),
    ROWS_REJECTED             NUMBER(38,0),
    EXECUTED_CODE_CHECKSUM    VARCHAR(128),
    CONSTRAINT PK_MODULE_INSTANCE PRIMARY KEY (MODULE_INSTANCE_ID)
);

CREATE TABLE IF NOT EXISTS <% database %>.OMD.MODULE_INSTANCE_EXECUTED_CODE
(
    CHECKSUM        VARCHAR(128)   NOT NULL,
    EXECUTED_CODE   VARCHAR,
    CONSTRAINT PK_MODULE_INSTANCE_EXECUTED_CODE PRIMARY KEY (CHECKSUM)
);

CREATE TABLE IF NOT EXISTS <% database %>.OMD.EVENT_LOG
(
    EVENT_ID            NUMBER(38,0)    NOT NULL,
    BATCH_INSTANCE_ID   NUMBER(38,0)    NOT NULL DEFAULT 0,
    MODULE_INSTANCE_ID  NUMBER(38,0)    NOT NULL DEFAULT 0,
    EVENT_TYPE_CODE     NUMBER(38,0)    NOT NULL DEFAULT 2,
    EVENT_TIMESTAMP     TIMESTAMP_NTZ   NOT NULL,
    EVENT_RETURN_CODE   VARCHAR(100),
    EVENT_DETAIL        VARCHAR(4000),
    ERROR_BITMAP        NUMBER(38,0),
    CONSTRAINT PK_EVENT_LOG PRIMARY KEY (EVENT_ID)
);

CREATE TABLE IF NOT EXISTS <% database %>.OMD.SOURCE_CONTROL
(
    SOURCE_CONTROL_ID   NUMBER(38,0)    NOT NULL,
    MODULE_ID           NUMBER(38,0)    NOT NULL,
    MODULE_INSTANCE_ID  NUMBER(38,0)    NOT NULL,
    INSERT_TIMESTAMP    TIMESTAMP_NTZ   NOT NULL,
    START_VALUE         VARCHAR(100),
    END_VALUE           VARCHAR(100),
    CONSTRAINT PK_SOURCE_CONTROL PRIMARY KEY (SOURCE_CONTROL_ID)
);

CREATE TABLE IF NOT EXISTS <% database %>.OMD.BATCH_PARAMETER
