/*
 * DIRECT Framework - Snowflake edition
 * 02 Tables and sequences
 *
 * The tables keep the names and columns of the SQL Server edition, in Snowflake
 * types. Identity columns are replaced by sequences; the procedures take the
 * next value explicitly so that the new identifier is known to the caller.
 * The scripts can be run again: existing tables and their data are kept.
 */

-- Reference data

