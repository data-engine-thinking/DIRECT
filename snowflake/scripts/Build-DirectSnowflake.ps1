#Requires -Version 7
<#
    Builds Direct_Snowflake.sql, the single deployment script of the Snowflake edition, from the
    numbered files in the sql folder. Run it after a change to one of those files and commit the result.

    With -Database, the `<% database %>` token is replaced and the result is written to the given
    -OutputFile (default Direct_Snowflake_<database>.sql): a script that can be pasted into a Snowsight
    worksheet, without the Snowflake CLI.

    Usage:
      ./Build-DirectSnowflake.ps1
      ./Build-DirectSnowflake.ps1 -Database MY_DB -OutputFile C:\temp\direct.sql
#>
param(
    [string]$Database,
    [string]$OutputFile
)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$sqlFolder = Join-Path $root 'sql'
$utf8 = [System.Text.UTF8Encoding]::new($false)

$files = Get-ChildItem $sqlFolder -Filter '*.sql' | Sort-Object Name
if ($files.Count -eq 0) { throw "No SQL files were found in $sqlFolder." }

$combined = [System.Text.StringBuilder]::new()
[void]$combined.AppendLine('/*')
[void]$combined.AppendLine(' * DIRECT Framework - Snowflake edition')
[void]$combined.AppendLine(' * Generated by scripts/Build-DirectSnowflake.ps1 from the files in the sql folder. Do not edit; edit those files.')
if ($Database) {
    [void]$combined.AppendLine(" * Repository database: $Database")
}
else {
    [void]$combined.AppendLine(' * Deploy with the Snowflake CLI: snow sql -c <connection> -f Direct_Snowflake.sql -D database=<name> --enable-templating STANDARD')
}
[void]$combined.AppendLine(' */')
[void]$combined.AppendLine()

foreach ($file in $files) {
    $content = [System.IO.File]::ReadAllText($file.FullName, $utf8)
    if ($Database) { $content = $content -replace '<%\s*database\s*%>', $Database }
    [void]$combined.AppendLine("-- >>> $($file.Name)")
    [void]$combined.AppendLine($content.TrimEnd())
    [void]$combined.AppendLine()
}

if (-not $OutputFile) {
    $OutputFile = if ($Database) { Join-Path $root "Direct_Snowflake_$Database.sql" } else { Join-Path $root 'Direct_Snowflake.sql' }
}

[System.IO.File]::WriteAllText($OutputFile, $combined.ToString(), $utf8)
Write-Host "Written $OutputFile from $($files.Count) file(s)." -ForegroundColor Green
